"""Places the narration takes on one timeline and writes the word times the film is cut to.

Each paragraph of story.json is one take (vo/pNN.mp3 + vo/pNN.json from tools/voice.py). Takes play exactly as
rendered, never cut inside: take N starts so its first word comes `pause` seconds after the previous take's last word.
Writes assets/lib/cues.js (window.CUES = {END, words: [[start, end, word, take]], takes}) and timeline.json.

  python tools/timeline.py           real takes from vo/
  python tools/timeline.py --fake    no voice yet: words timed from the text at about 155 words a minute (drafts only)
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIRST = 0.25      # the first word starts here
PAUSE = 0.30      # default pause between paragraphs (last word end -> next first word)
TAIL = 1.2        # picture after the last word


def fake_words(text, t0):
    out, t = [], t0
    for w in text.split():
        syl = max(1, len(re.findall(r"[aeiouy]+", w.lower())))
        d = 0.12 + 0.13 * syl
        out.append([round(t, 4), round(t + d, 4), w])
        t += d + 0.06 + (0.28 if re.search(r"[.!?]$", w) else 0.12 if re.search(r"[,;:]$", w) else 0)
    return out


def main():
    fake = "--fake" in sys.argv
    story = json.load(open(os.path.join(ROOT, "story.json"), encoding="utf-8"))
    paras = story["paragraphs"]
    takes, words, prev_end = [], [], None
    for i, p in enumerate(paras):
        pid = "p%02d" % (i + 1)
        pause = p.get("pause", PAUSE)
        if fake:
            w = fake_words(p["text"], 0.05)
            keep = w[-1][1] + 0.15
            f = None
        else:
            meta = os.path.join(ROOT, "vo", pid + ".json")
            if not os.path.exists(meta):
                raise SystemExit(f"missing vo/{pid}.json: run tools/voice.py first (or --fake for a draft)")
            m = json.load(open(meta, encoding="utf-8"))
            w, keep, f = m["words"], m["keep"], m["file"]
        onset = FIRST if prev_end is None else prev_end + pause
        start = round(onset - w[0][0], 4)
        takes.append({"pid": pid, "start": start, "keep": keep, "file": f, "speaker": p.get("speaker"), "pitch": p.get("pitch", 0),
                      "first": round(start + w[0][0], 4), "last": round(start + w[-1][1], 4), "mood": p.get("mood", "playful")})
        for s, e, word in w:
            words.append([round(start + s, 4), round(start + e, 4), word, pid])
        prev_end = start + w[-1][1]
    END = round(prev_end + story.get("tail", TAIL), 4)
    cues = {"END": END, "words": words, "takes": takes, "fake": fake}
    js = os.path.join(ROOT, "assets", "lib", "cues.js")
    with open(js, "w", encoding="utf-8") as fh:
        fh.write("/* Generated by tools/timeline.py: do not edit by hand. */\n")
        fh.write("window.CUES = " + json.dumps(cues, separators=(",", ":")) + ";\n")
    json.dump(cues, open(os.path.join(ROOT, "timeline.json"), "w", encoding="utf-8"), indent=1)
    print(f"{len(takes)} takes, {len(words)} words, {END:.2f} s{'  (FAKE timing: draft only)' if fake else ''}")
    for tk in takes:
        print(f"  {tk['pid']} {tk['first']:7.2f}-{tk['last']:7.2f}")


if __name__ == "__main__":
    main()
